defmodule ExOpenAI.ContentProvenanceChecks do
  @moduledoc """
  Functions for the OpenAI content_provenance_checks API.
  """
  (
    @doc """
    Check whether an image or audio file contains known OpenAI provenance signals. [Learn more about content provenance](https://platform.openai.com/api/docs/guides/content-provenance).

    If `not_detected`, it means the tool did not find supported signals in the uploaded file. The content could still have been generated by OpenAI if the metadata was stripped or has evidence of tampering, the watermark was degraded, it comes from a legacy generation model, or it was created before provenance signals were available. Content could also still be AI-generated by another company's model, which the tool currently does not detect.

    ## Options

    * `file` - **optional** - `binary() | {String.t(), binary()}`
      The image or audio file to check for supported OpenAI provenance signals.
      Format: `binary`
    """
    (
      @type createcontentprovenancecheck_opt() ::
              {:file, binary() | {String.t(), binary()}} | ExOpenAI.request_option()
      @spec createcontentprovenancecheck(opts :: [createcontentprovenancecheck_opt()]) ::
              {:ok, ExOpenAI.Components.ProvenanceResource.t()} | {:error, any()}
    )

    def createcontentprovenancecheck(opts \\ []) do
      url = "/content_provenance_checks"
      query_params = Keyword.take(opts, [])
      url = ExOpenAI.Query.append(url, query_params)
      body_params = []
      optional_body_params = Keyword.take(opts, [:file])
      body_params = body_params ++ optional_body_params
      optional_params_to_drop = [:file] |> Enum.reject(&(&1 == :stream))
      opts = Keyword.drop(opts, optional_params_to_drop)

      convert_response = fn response ->
        ExOpenAI.Codegen.ResponseConverter.convert_response(
          response,
          %ExOpenAI.Codegen.DocsParser.Schema{ref: "#/components/schemas/ProvenanceResource"}
        )
      end

      body_params = ExOpenAI.Client.prepare_multipart(body_params, [:file], %{})

      ExOpenAI.Config.http_client().api_call(
        :post,
        url,
        body_params,
        :"multipart/form-data",
        opts,
        convert_response
      )
    end
  )
end
